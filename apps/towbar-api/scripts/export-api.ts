import { z } from "zod";
import { keyCeiling } from "@workspace/towbar-access";
import { format } from "prettier";
import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import {
  referenceCategories,
  referenceGroup,
  sectionOrder,
} from "../src/areas/external-api/reference-groups.js";
// Exporting route schemas performs no database or network operations.
process.env.DATABASE_TOWBAR_URL ??=
  "postgres://docs:docs@localhost/towbar_docs";
process.env.TOWBAR_CREDENTIALS_KEY ??= Buffer.alloc(32, 1).toString("base64");
process.env.TOWBAR_INTERNAL_HMAC_SECRET ??=
  "documentation-only-placeholder-secret";
const { createOpenApiDocument, operations } =
  await import("../src/areas/external-api/catalogue.js");
const { mcpTools } = await import("../src/areas/external-api/mcp-tools.js");
const root = resolve(import.meta.dirname, "../../..");
const doc = createOpenApiDocument("https://towbar-api.example.com/v1/api");
const output = await format(JSON.stringify(doc), { parser: "json" });
const target = resolve(root, "docs/api-reference/openapi.json");
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error("OpenAPI snapshot is stale. Run pnpm docs:api.");
} else await writeFile(target, output);
const groups = new Map<string, Map<string, string[]>>();
const generatedPages = new Set<string>();
for (const op of operations) {
  const route = `api-reference/${op.name}`;
  generatedPages.add(`${op.name}.mdx`);
  const path = op.path.replace(/:([A-Za-z]+)/g, "{$1}");
  const description = `${op.summary} through the Towbar REST API.`;
  const body = await format(
    `---\ntitle: ${JSON.stringify(op.summary)}\ndescription: ${JSON.stringify(description)}\nplayground: simple\nopenapi: ${JSON.stringify(`/api-reference/openapi.json ${op.method} ${path}`)}\n---\n\n{/* Generated by export-api.ts */}\n\nRequired permissions: ${op.permissions.join(", ")}. Personal keys are capped by their owner’s current team role.\n\n${op.idempotencyKey ? "Supply an Idempotency-Key for this action. An accepted request may continue asynchronously; poll the returned ID.\n\n" : ""}See [request conventions](/api-reference/overview) and [automation workflows](/docs/api/workflows). MCP clients use the task-oriented [tool reference](/mcp-reference/overview).\n`,
    { parser: "mdx" },
  );
  const target = resolve(root, `docs/${route}.mdx`);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== body)
      throw new Error(`Stale API page: ${route}`);
  } else {
    await mkdir(resolve(root, "docs/api-reference"), { recursive: true });
    await writeFile(target, body);
  }
  const [category, group] = referenceGroup(op.path);
  if (!groups.has(category)) groups.set(category, new Map());
  const subgroups = groups.get(category)!;
  if (!subgroups.has(group)) subgroups.set(group, []);
  subgroups.get(group)!.push(route);
}
// Remove only endpoint pages owned by this exporter when an operation becomes browser-only.
for (const file of await readdir(resolve(root, "docs/api-reference"))) {
  if (!file.endsWith(".mdx") || generatedPages.has(file)) continue;
  const path = resolve(root, "docs/api-reference", file);
  const existing = await readFile(path, "utf8");
  if (
    !existing.includes("\nMCP tool: `") &&
    !existing.includes("Generated by export-api.ts")
  )
    continue;
  if (process.argv.includes("--check"))
    throw new Error(`Obsolete API page: ${file}. Run pnpm docs:api.`);
  await unlink(path);
}
const toolGroups: Record<string, string> = {
  workspace: "Workspace",
  inventory: "Discovery",
  repository: "Discovery",
  source: "Repositories",
  manifest: "Repositories",
  retirement: "Repositories",
  workload: "Services and datastores",
  autodeploy: "Services and datastores",
  deployment: "Deployments",
  server: "Servers",
  monitoring: "Scout Agent",
  logs: "Centralized logs",
  alerts: "Scout Alerts",
  performance: "Scout Agent",
  secrets: "Secrets",
  backup: "Backups and restores",
  volume: "Backups and restores",
  restore: "Backups and restores",
  preview: "Preview environments",
  integration: "Integrations",
  github: "Integrations",
  aws: "Integrations",
};
const toolSections = new Map<
  string,
  { title: string; route: string; name: string }[]
>();
const mcpDirectory = resolve(root, "docs/mcp-reference");
await mkdir(mcpDirectory, { recursive: true });
const toolPages = new Set(["overview.mdx"]);
for (const tool of mcpTools) {
  const group = toolGroups[tool.name.split("_")[1]!]!;
  if (!group) throw new Error(`Missing MCP documentation group: ${tool.name}`);
  const schema = z.toJSONSchema(tool.input, {
    io: "input",
    unrepresentable: "any",
  });
  const route = `mcp-reference/${tool.name}`;
  toolPages.add(`${tool.name}.mdx`);
  const access = tool.permissions.some(
    (permission) => !keyCeiling("admin", "edit", false).includes(permission),
  )
    ? "Administrator"
    : tool.readOnly
      ? "Read-only"
      : "Write";
  const body = await format(
    `---
title: ${JSON.stringify(tool.title)}
sidebarTitle: ${JSON.stringify(tool.name)}
description: ${JSON.stringify(`${tool.title} through the Towbar MCP interface.`)}
---

{/* Generated by export-api.ts from the registered MCP tool. */}

\`${tool.name}\`

${tool.description}

## Access and behavior

Choose **${access}** when approving the [MCP connection](/docs/api/mcp). Your current team role and approved permissions constrain access.

Required permissions: ${tool.permissions.map((permission) => `\`${permission}\``).join(", ")}.

| Annotation | Value |
| --- | --- |
| Read-only | ${tool.readOnly} |
| Destructive | ${tool.destructive} |
| Idempotent | ${tool.idempotent} |

${tool.destructive ? "Review the target and effect with the user before running this tool. An idempotent annotation does not make an action reversible.\n" : ""}
## Arguments

The schema below comes from the runtime input validator. Required fields, enum values, defaults, and limits are preserved. Semantic constraints described by the tool still apply.

\`\`\`json
${JSON.stringify(schema, null, 2)}
\`\`\`

## Result

Successful calls return structured \`result\` data with a matching JSON text fallback. Failures set \`isError\`. An accepted operation can continue asynchronously; inspect the returned operation or deployment ID and use the matching inspect tool to confirm its outcome. See [automation workflows](/docs/api/workflows) for worked sequences.

Browse the [MCP tool reference](/mcp-reference/overview) for related tools.
`,
    { parser: "mdx" },
  );
  const target = resolve(root, `docs/${route}.mdx`);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== body)
      throw new Error(`Stale MCP page: ${route}`);
  } else await writeFile(target, body);
  if (!toolSections.has(group)) toolSections.set(group, []);
  toolSections.get(group)!.push({ title: tool.title, name: tool.name, route });
}
for (const file of await readdir(mcpDirectory)) {
  if (!file.endsWith(".mdx") || toolPages.has(file)) continue;
  const target = resolve(mcpDirectory, file);
  if (!(await readFile(target, "utf8")).includes("Generated by export-api.ts"))
    continue;
  if (process.argv.includes("--check"))
    throw new Error(`Obsolete MCP page: ${file}`);
  await unlink(target);
}
const toolsDoc = await format(
  `---
title: MCP tool reference
description: Individual Towbar tools, permissions, risk annotations, and runtime argument schemas.
---

Towbar registers ${mcpTools.length} task-oriented tools independently of HTTP routes. [Connect an MCP client](/docs/api/mcp) through OAuth before using them. Discovery filters tools by the approved Read-only, Write, or Administrator access and your current workspace role. Account management, SSH terminals, and plaintext credential reveal remain browser-only.

Each tool page includes its exact name, permissions, risk annotations, and generated argument schema. Use [automation workflows](/docs/api/workflows) for sequences across tools.

Inventory and history tools return bounded pages with continuation fields. Histories backed by live inventories are best-effort pages, not snapshot cursors; concurrent changes can shift offsets.

${Array.from(toolSections, ([group, tools]) => `## ${group}\n\n${tools.map(({ title, route, name }) => `- [\`${name}\`](/${route}): ${title}`).join("\n")}`).join("\n\n")}
`,
  { parser: "mdx" },
);
const toolsPath = resolve(mcpDirectory, "overview.mdx");
if (process.argv.includes("--check")) {
  if ((await readFile(toolsPath, "utf8")) !== toolsDoc)
    throw new Error("MCP reference is stale. Run pnpm docs:api.");
} else await writeFile(toolsPath, toolsDoc);
console.log(`MCP: ${mcpTools.length} task-oriented tools`);

const configPath = resolve(root, "docs/site.json");
const config = JSON.parse(await readFile(configPath, "utf8"));
const navigationItems = config.navigation.dropdowns ?? config.navigation.tabs;
const navigationLabel = config.navigation.dropdowns ? "dropdown" : "tab";
const navigation = {
  [navigationLabel]: "API & MCP",
  ...(navigationLabel === "dropdown" ? { icon: "square-terminal" } : {}),
  // Each MDX page references its spec; a tab-level spec also generates duplicate groups.
  groups: [
    {
      group: "Connect a client",
      pages: ["docs/api/authentication", "docs/api/mcp"],
    },
    { group: "Automation workflows", pages: ["docs/api/workflows"] },
    {
      group: "MCP reference",
      pages: [
        "mcp-reference/overview",
        ...Array.from(toolSections, ([group, tools]) => ({
          group,
          pages: tools.map(({ route }) => route),
        })),
      ],
    },
    {
      group: "HTTP reference",
      pages: [
        "api-reference/overview",
        ...referenceCategories.map((category) => ({
          group: category,
          pages: Array.from(groups.get(category) ?? [], ([group, pages]) => ({
            group,
            pages,
          })).sort(
            (a, b) =>
              sectionOrder.indexOf(a.group) - sectionOrder.indexOf(b.group),
          ),
        })),
      ],
    },
  ],
};
const current = navigationItems.findIndex(
  (item: Record<string, string>) => item[navigationLabel] === "API & MCP",
);
if (process.argv.includes("--check")) {
  if (JSON.stringify(navigationItems[current]) !== JSON.stringify(navigation))
    throw new Error("API navigation is stale. Run pnpm docs:api.");
} else {
  if (current >= 0) navigationItems[current] = navigation;
  else navigationItems.push(navigation);
  await writeFile(
    configPath,
    await format(JSON.stringify(config), { parser: "json" }),
  );
}
console.log(`OpenAPI: ${operations.length} operations`);
